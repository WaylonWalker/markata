package plugins

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/WaylonWalker/markata/pkg/models"
)

const shortsRoutesFile = ".markata-shorts-routes.json"

// shortsRouteLedger records the exact routes owned by the previous successful
// publication, including feeds that may no longer appear in configuration.
type shortsRouteLedger struct {
	Version int               `json:"version"`
	Routes  map[string]string `json:"routes"`
}

func shortsPublishedOwner(outputDir, route string) string {
	if validateShortsPath(route) != nil {
		return ""
	}
	marker := filepath.Join(outputDir, strings.Trim(route, "/"), "data", "index.json")
	data, err := os.ReadFile(marker)
	if err != nil {
		return ""
	}
	var index struct {
		FeedSlug string `json:"feed_slug"`
	}
	if json.Unmarshal(data, &index) != nil {
		return ""
	}
	return index.FeedSlug
}

// loadPreviousShortsRoutes reads the last successfully published routes.
// On first use, migrate only the legacy default /shorts/ route when its own
// marker identifies a Shorts feed.
func loadPreviousShortsRoutes(outputDir, ledgerPath string) (shortsRouteLedger, error) {
	previous := shortsRouteLedger{Version: 1, Routes: make(map[string]string)}
	data, err := os.ReadFile(ledgerPath)
	switch {
	case err == nil:
		if err := json.Unmarshal(data, &previous); err != nil || previous.Version != 1 {
			return previous, fmt.Errorf("invalid Shorts route ledger %s", ledgerPath)
		}
		if previous.Routes == nil {
			return previous, fmt.Errorf("invalid Shorts route ledger routes in %s", ledgerPath)
		}
	case os.IsNotExist(err):
		if slug := shortsPublishedOwner(outputDir, "/shorts/"); slug != "" {
			previous.Routes["/shorts/"] = slug
		}
	default:
		return previous, err
	}
	return previous, nil
}

func shortsReservedRoutes(feeds []models.FeedConfig, posts []*models.Post) map[string]bool {
	reserved := make(map[string]bool)
	for i := range feeds {
		feed := &feeds[i]
		if feed.Formats.HTML {
			route := "/" + strings.Trim(feed.Slug, "/") + "/"
			if feed.Slug == "" {
				route = "/"
			}
			reserved[route] = true
		}
	}
	for _, post := range posts {
		if post != nil && !post.Skip && !post.Draft && post.Published {
			reserved["/"+strings.Trim(post.Slug, "/")+"/"] = true
		}
	}
	return reserved
}

func shortsChunkFilename(name string) bool {
	if len(name) != len("0000.json") || !strings.HasSuffix(name, ".json") {
		return false
	}
	for _, ch := range name[:4] {
		if ch < '0' || ch > '9' {
			return false
		}
	}
	return true
}

// cleanRepurposedShortsData only removes files generated by Shorts, not an
// entire data directory which a new feed or post may have populated.
func cleanRepurposedShortsData(outputDir, route string) error {
	dataDir := filepath.Join(outputDir, strings.Trim(route, "/"), "data")
	entries, err := os.ReadDir(dataDir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() || (entry.Name() != "index.json" && !shortsChunkFilename(entry.Name())) {
			continue
		}
		if err := os.Remove(filepath.Join(dataDir, entry.Name())); err != nil {
			return err
		}
	}
	remaining, err := os.ReadDir(dataDir)
	if err != nil {
		return err
	}
	if len(remaining) == 0 {
		return os.Remove(dataDir)
	}
	return nil
}

func prunePreviousShortsRoutes(outputDir string, previous, current map[string]string, reserved map[string]bool) error {
	for route, owner := range previous {
		if _, stillPublished := current[route]; stillPublished {
			continue
		}
		if shortsPublishedOwner(outputDir, route) != owner {
			continue
		}
		if reserved[route] {
			// Preserve the replacement publisher's HTML and unrelated data.
			if err := cleanRepurposedShortsData(outputDir, route); err != nil {
				return err
			}
			continue
		}
		if err := cleanupDisabledShorts(outputDir, route, owner); err != nil {
			return err
		}
	}
	return nil
}

// reconcileShortsRoutes runs only after all current feed writes complete.
// Compare the current route set with the previous successful build's owners.
// Never remove routes whose marker no longer identifies the original feed.
func reconcileShortsRoutes(outputDir string, feeds []models.FeedConfig, posts []*models.Post) error {
	current := make(map[string]string)
	for i := range feeds {
		feed := &feeds[i]
		if feed.HasView(models.FeedViewShorts) {
			current[feed.ShortsURL()] = feed.Slug
		}
	}
	ledgerPath := filepath.Join(outputDir, shortsRoutesFile)
	previous, err := loadPreviousShortsRoutes(outputDir, ledgerPath)
	if err != nil {
		return err
	}
	if err := prunePreviousShortsRoutes(outputDir, previous.Routes, current, shortsReservedRoutes(feeds, posts)); err != nil {
		return err
	}
	if len(current) == 0 && len(previous.Routes) == 0 {
		return nil
	}
	encoded, err := json.Marshal(shortsRouteLedger{Version: 1, Routes: current})
	if err != nil {
		return err
	}
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(outputDir, ".shorts-routes-*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(append(encoded, '\n')); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), ledgerPath)
}
