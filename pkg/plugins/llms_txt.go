package plugins

import (
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/WaylonWalker/markata-go/pkg/lifecycle"
	"github.com/WaylonWalker/markata-go/pkg/models"
)

const llmsTXTPluginName = "llms_txt"
const llmsTXTMarker = "<!-- Generated by markata-go llms_txt -->"
const defaultLLMsTXTMaxPages = 30

// LLMsTXTPlugin writes a compact, public-content index at /llms.txt.
// A source post with slug "llms" or a project static/llms.txt takes precedence.
type LLMsTXTPlugin struct{}

func NewLLMsTXTPlugin() *LLMsTXTPlugin { return &LLMsTXTPlugin{} }
func (p *LLMsTXTPlugin) Name() string  { return llmsTXTPluginName }

func (p *LLMsTXTPlugin) Priority(stage lifecycle.Stage) int {
	if stage == lifecycle.StageWrite {
		// Run after publish_html, static_assets, and sitemap.
		return lifecycle.PriorityLast
	}
	return lifecycle.PriorityDefault
}

func (p *LLMsTXTPlugin) Write(m *lifecycle.Manager) error {
	cfg := m.Config()
	if cfg == nil {
		return fmt.Errorf("llms_txt: missing site configuration")
	}
	output := filepath.Join(cfg.OutputDir, "llms.txt")
	enabled, maxPages := llmsTXTOptions(cfg)

	if !enabled {
		return removeGeneratedLLMsTXT(output)
	}

	// Do not overwrite a published, hand-authored llms.md or a project static
	// llms.txt. These are both already supported by markata-go.
	for _, post := range m.Posts() {
		if post != nil && post.Slug == "llms" && post.Published && !post.Draft && !post.Skip &&
			resolvePostFormats(post, cfg).Text {
			return nil
		}
	}
	staticFile := filepath.Join(NewStaticAssetsPlugin().projectStaticDir(cfg), "llms.txt")
	if _, err := os.Stat(staticFile); err == nil {
		return nil
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("llms_txt: checking project static file: %w", err)
	}

	// Preserve manually managed output/llms.txt, but refresh generated content
	// on every build. In particular, never mistake a previous build for a
	// hand-authored file on a warm/incremental build.
	if info, err := os.Lstat(output); err == nil {
		// Do not follow a symlink placed at the generated file's path.
		if !info.Mode().IsRegular() {
			return fmt.Errorf("llms_txt: refusing to replace non-regular output %q", output)
		}
		data, err := os.ReadFile(output)
		if err != nil {
			return fmt.Errorf("llms_txt: reading existing output: %w", err)
		}
		if !strings.Contains(string(data), llmsTXTMarker) {
			return nil
		}
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("llms_txt: inspecting output: %w", err)
	}
	if err := os.MkdirAll(cfg.OutputDir, 0o755); err != nil {
		return fmt.Errorf("llms_txt: creating output directory: %w", err)
	}

	content := buildLLMsTXT(m, maxPages)
	//nolint:gosec // This published index must be readable by the static web server.
	if err := os.WriteFile(output, []byte(content), 0o644); err != nil {
		return fmt.Errorf("llms_txt: writing output: %w", err)
	}
	return nil
}

func removeGeneratedLLMsTXT(path string) error {
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("llms_txt: inspecting disabled output: %w", err)
	}
	if !info.Mode().IsRegular() {
		return nil
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("llms_txt: reading disabled output: %w", err)
	}
	if strings.Contains(string(data), llmsTXTMarker) {
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("llms_txt: removing disabled generated output: %w", err)
		}
	}
	return nil
}

func llmsTXTOptions(cfg *lifecycle.Config) (enabled bool, maxPages int) {
	enabled, maxPages = true, defaultLLMsTXTMaxPages
	if cfg == nil || cfg.Extra == nil {
		return enabled, maxPages
	}
	raw, ok := cfg.Extra[llmsTXTPluginName].(map[string]interface{})
	if !ok {
		return enabled, maxPages
	}
	if v, ok := raw["enabled"].(bool); ok {
		enabled = v
	}
	switch n := raw["max_pages"].(type) {
	case int:
		maxPages = n
	case int64:
		maxPages = int(n)
	case float64:
		maxPages = int(n)
	}
	if maxPages < 1 {
		maxPages = defaultLLMsTXTMaxPages
	}
	if maxPages > 100 {
		maxPages = 100
	}
	return enabled, maxPages
}

//nolint:gocyclo // Keep the generation and filtering rules together for auditable privacy boundaries.
func buildLLMsTXT(m *lifecycle.Manager, maxPages int) string {
	cfg := m.Config()
	siteURL := ""
	if cfg.Extra != nil {
		if raw, ok := cfg.Extra["url"].(string); ok {
			u, err := url.Parse(strings.TrimSpace(raw))
			if err == nil && (u.Scheme == schemeHTTPS || u.Scheme == schemeHTTP) && u.Host != "" &&
				u.RawQuery == "" && u.Fragment == "" {
				siteURL = strings.TrimRight(u.String(), "/")
			}
		}
	}

	title := llmsTXTPlain(getSiteTitle(cfg), 120)
	description := llmsTXTPlain(getSiteDescription(cfg), 300)
	if description == "" {
		description = "A concise guide to this site's publicly published content."
	}

	docs := make([]*models.Post, 0)
	other := make([]*models.Post, 0)
	seen := make(map[string]bool)
	for _, post := range m.Posts() {
		if post == nil || !post.Published || post.Draft || post.Skip || post.Private ||
			sitemapPostNoindex(post) || post.Slug == "llms" {
			continue
		}
		href := post.Href
		if href == "" || href == "/" || !strings.HasPrefix(href, "/") || strings.HasPrefix(href, "//") ||
			post.PlainTitle() == "" || seen[href] {
			continue
		}
		u, err := url.Parse(href)
		if err != nil || u.Host != "" || u.Scheme != "" || u.RawQuery != "" || u.Fragment != "" {
			continue
		}
		formats := resolvePostFormats(post, cfg)
		if !formats.Markdown && !formats.IsHTMLEnabled() {
			continue
		}
		seen[href] = true
		if strings.HasPrefix(href, "/docs/") {
			docs = append(docs, post)
		} else {
			other = append(other, post)
		}
	}
	latestFirst := func(posts []*models.Post) {
		sort.Slice(posts, func(i, j int) bool {
			a, b := posts[i], posts[j]
			if a.Date != nil && b.Date != nil && !a.Date.Equal(*b.Date) {
				return a.Date.After(*b.Date)
			}
			if (a.Date != nil) != (b.Date != nil) {
				return a.Date != nil
			}
			return a.Href < b.Href
		})
	}
	latestFirst(docs)
	latestFirst(other)

	// Reserve at most a third of the slots for documentation; any unused
	// capacity is filled with other pages so small sites still get a useful index.
	docsLimit := maxPages / 3
	if docsLimit == 0 && maxPages > 0 {
		docsLimit = 1
	}
	if docsLimit > len(docs) {
		docsLimit = len(docs)
	}
	selectedDocs := docs[:docsLimit]
	remaining := maxPages - len(selectedDocs)
	if remaining > len(other) {
		remaining = len(other)
	}
	selectedOther := other[:remaining]
	remaining = maxPages - len(selectedDocs) - len(selectedOther)
	if remaining > 0 && docsLimit < len(docs) {
		extra := len(docs) - docsLimit
		if extra > remaining {
			extra = remaining
		}
		selectedDocs = docs[:docsLimit+extra]
	}

	var out strings.Builder
	fmt.Fprintf(&out, "# %s\n\n> %s\n\n%s\n\n", llmsTXTPlainTitle(title), description, llmsTXTMarker)
	out.WriteString("## Site\n\n")
	fmt.Fprintf(&out, "- [Home](%s/): Site homepage\n\n", siteURL)

	writeSection := func(name string, posts []*models.Post) {
		if len(posts) == 0 {
			return
		}
		fmt.Fprintf(&out, "## %s\n\n", name)
		for _, post := range posts {
			href := post.Href
			if resolvePostFormats(post, cfg).Markdown && strings.HasSuffix(href, "/") {
				href = strings.TrimSuffix(href, "/") + ".md"
			}
			// Escape URL characters that might terminate Markdown link syntax.
			parsed, err := url.Parse(href) // Validated when selecting posts above.
			if err != nil {
				continue
			}
			href = parsed.EscapedPath()
			name := llmsTXTLinkLabel(llmsTXTPlain(post.PlainTitle(), 120))
			note := ""
			if post.Description != nil {
				note = llmsTXTPlain(*post.Description, 180)
			}
			if note == "" {
				fmt.Fprintf(&out, "- [%s](%s%s)\n", name, siteURL, href)
			} else {
				fmt.Fprintf(&out, "- [%s](%s%s): %s\n", name, siteURL, href, note)
			}
		}
		out.WriteByte('\n')
	}
	writeSection("Documentation", selectedDocs)
	writeSection("Recent Content", selectedOther)

	if _, err := os.Stat(filepath.Join(cfg.OutputDir, "sitemap.xml")); err == nil {
		out.WriteString("## Optional\n\n")
		fmt.Fprintf(&out, "- [Sitemap](%s/sitemap.xml): Complete index of publicly accessible pages\n\n", siteURL)
	}
	return out.String()
}

func llmsTXTPlain(value string, maxRunes int) string {
	clean := strings.Join(strings.Fields(value), " ")
	runes := []rune(clean)
	if len(runes) > maxRunes {
		return string(runes[:maxRunes]) + "…"
	}
	return clean
}

func llmsTXTPlainTitle(value string) string {
	return strings.NewReplacer("#", "\\#", "[", "\\[", "]", "\\]").Replace(value)
}

func llmsTXTLinkLabel(value string) string {
	return strings.NewReplacer("\\", "\\\\", "[", "\\[", "]", "\\]").Replace(value)
}

var (
	_ lifecycle.Plugin         = (*LLMsTXTPlugin)(nil)
	_ lifecycle.WritePlugin    = (*LLMsTXTPlugin)(nil)
	_ lifecycle.PriorityPlugin = (*LLMsTXTPlugin)(nil)
)
